"""End-to-end demonstration: from initial corpus to final answer.

Runs the whole challenge in an isolated sandbox (temporary submissions directory,
demo HMAC secret if none is configured) and writes a transcript to
docs/DEMO_TRANSCRIPT.md:

 1. organiser constructs and validates the challenge;
 2. participants see the neutral corpus;
 3. a team submits an initial graph (with AI-assisted mistakes) and gets an aggregate score;
 4. the organiser-side demo shows how the injected and decoy edges got in;
 5. the team revises its graph and resubmits;
 6. the team identifies the hidden conceptual connection (Stage 3 shows the same reasoning);
 7. the team submits its one-shot final answer (no feedback before the deadline);
 8. after the deadline the organiser views the protected answer key and results.

Usage:  python scripts/demo_walkthrough.py
"""
from __future__ import annotations

import datetime as dt
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

OUT = ROOT / "docs" / "DEMO_TRANSCRIPT.md"


def main() -> int:
    tmp = tempfile.mkdtemp(prefix="ul-demo-")
    os.environ["UL_SUBMISSIONS_DIR"] = tmp
    # Always a throwaway secret: the committed transcript must never contain a flag valid under the real secret.
    secret = "demo-secret-not-for-workshop-use-0123456789"
    from challenge import participant_data, paths
    from challenge.document_reader import extract_text
    from challenge.naive_assistant import guarded_extract, naive_extract
    from challenge.submission import ParticipantBackend
    from challenge.submission_store import SubmissionStore
    from graph.builder import build_graph, load_master_records
    from graph.pipeline import run_pipeline
    from graph.validation import errors, validate_records
    from scoring.flag_validator import FinalSubmissionService, build_flag_registry
    from scoring.graph_scorer import GraphScorer

    L: list[str] = []
    w = L.append
    w("# Demonstration transcript\n")
    w(f"_Generated by `scripts/demo_walkthrough.py` on {dt.date.today().isoformat()} in an isolated sandbox. "
      "Sections marked **[ORGANISER]** show protected information that participants never see._\n")

    # 1 ------------------------------------------------------------------
    w("## 1. [ORGANISER] Construct and validate the challenge\n")
    rec = load_master_records()
    errs = errors(validate_records(rec))
    g = build_graph(rec)
    n_types = {}
    for n in rec["nodes"]:
        n_types[n["type"]] = n_types.get(n["type"], 0) + 1
    w(f"- Master graph: **{len(rec['nodes'])} nodes** {n_types}, **{len(rec['edges'])} typed edges**, validation errors: **{len(errs)}**.")
    canon = paths.read_json(paths.CANONICAL_PATH)
    w(f"- Canonical path (secret): `{' -> '.join(canon['path_participant_ids'])}`")
    for a in paths.read_json(paths.ALTERNATIVE_PATHS)["paths"]:
        w(f"- Verified alternative {a['id']}: `{' -> '.join(a['path_participant_ids'])}` ({a['label']})")
    w(f"- Decoys (secret): {', '.join(d['participant_id'] for d in paths.read_json(paths.DECOYS)['decoys'])}")
    w(f"- Synthetic injections (secret): " + "; ".join(f"{a['id']} on {a['host_card_participant_id']} -> induces `{' '.join(a['induced_edge'])}`"
                                                    for a in paths.read_json(paths.INJECTIONS)["annotations"]))
    scorer = GraphScorer.from_answer_key()
    classes = {}
    for c in scorer.classes.values():
        classes[c] = classes.get(c, 0) + 1
    w(f"- Scoring universe: {len(scorer.classes)} candidate edges, classes {classes}\n")

    # 2 ------------------------------------------------------------------
    w("## 2. Participants see the neutral corpus\n")
    info = participant_data.load_challenge_info()
    w(f"Starting paper given to every team: **{info['starting_paper']}**. Every card has the same fields; no roles are shown.\n")
    w("| ID | Year | Domain | Title |\n|---|---|---|---|")
    for c in participant_data.load_corpus():
        w(f"| {c['participant_id']} | {c['year']} | {c['domain']} | {c['title']} |")
    w("")

    # 3 ------------------------------------------------------------------
    store = SubmissionStore(tmp)
    team = store.create_team("Team Demo", ["Student A", "Student B"])
    be = ParticipantBackend(store)
    w("## 3. A team submits an initial graph\n")
    w(f"Organiser created team `{team['team_id']}`; the team signs in with its code. Their first attempt "
      "(`data/samples/sample_submission_initial.csv`) mixes real citations with edges suggested by an AI assistant "
      "that read the challenge cards, and with surface-similarity guesses:\n")
    init = (paths.SAMPLES_DIR / "sample_submission_initial.csv").read_text(encoding="utf-8")
    w("```csv\n" + init.strip() + "\n```\n")
    r1 = be.submit_graph(team["team_id"], init)
    w(f"Score returned to the team (aggregate only): `{r1['score']}`\n")

    # 4 ------------------------------------------------------------------
    w("## 4. [ORGANISER] Why that score was low: the AI-injection demo\n")
    texts = {p.stem: extract_text(p) for p in sorted(paths.CARDS_DIR.glob("P*.pdf"))}
    naive = naive_extract(texts)
    guarded, quarantined = guarded_extract(texts)
    w("A naive assistant that believes every sentence in the card PDFs (including white-on-white text) adds:\n")
    for e in naive:
        w(f"- `{e['source_id']} {e['relationship_type']} {e['target_id']}` from card {e['from_document']} (status it claims: {e['status']})")
    w(f"\nThe guarded pipeline quarantines {len(quarantined)} instruction-like sentence(s) and labels all remaining proposals AI_PROPOSED.")
    s1 = store.graph_submissions(team["team_id"])[0]["scores"]["all"]
    w(f"\nOrganiser breakdown of the initial submission (all edges): TP={s1['tp']}, ordinary FP={s1['fp_ordinary']}, "
      f"decoy FP={s1['fp_decoy']}, injection FP={s1['fp_injection']} -> weighted FP {s1['weighted_fp']} "
      f"(weights {scorer.weights}).\n")

    # 5 ------------------------------------------------------------------
    w("## 5. The team revises its graph\n")
    w("After checking each claim against the papers, the team drops the decoy and injected edges, fixes P08's method "
      "(it explains why it does *not* use neighbor-joining, p.7) and adds methodological and interpretive edges with page references.\n")
    rev = (paths.SAMPLES_DIR / "sample_submission_revised.csv").read_text(encoding="utf-8")
    t0 = dt.datetime.fromisoformat(store.graph_submissions(team["team_id"])[0]["submitted_at"])
    ok, why = store.can_submit_graph(team["team_id"], be.config, at=t0 + dt.timedelta(seconds=5))
    w(f"(An immediate resubmission is refused by the rate limit: \"{why}\")\n")
    # bypass the wall-clock rate limit for the scripted demo by recording directly with a later timestamp
    from scoring.graph_scorer import parse_submission

    parsed = parse_submission(rev, participant_data.participant_infos())
    res = scorer.score(parsed.edges)
    store.record_graph_submission(team["team_id"], parsed.edges, parsed.evidence, res, at=t0 + dt.timedelta(minutes=12))
    w(f"Revised score returned to the team: `{res.participant_view('public')}`\n")
    w("| attempt | public weighted F1 | precision | recall |\n|---|---|---|---|")
    for i, h in enumerate(be.history(team["team_id"]), 1):
        w(f"| {i} | {h['weighted_f1']} | {h['weighted_precision']} | {h['recall']} |")
    w("")

    # 6 ------------------------------------------------------------------
    w("## 6. Identifying the hidden conceptual connection\n")
    w("The team's reasoning (what students are expected to reconstruct):\n")
    w("1. P05 infers a hidden multicast tree using only what the receivers (leaves) observe.")
    w("2. P12 cites P05 and states its routing-topology problem 'is similar to the phylogenetic inference problem' (p.5), "
      "then runs neighbor-joining (Alg. 1, p.13).")
    w("3. P08 applies phylogenetic tree-metric techniques to the same network problem and cites P03 (ref. [24]).")
    w("4. P03 (evolutionary biology) reconstructs hidden ancestors from distances between observed species: the same "
      "leaf-only hidden-tree principle, in a different discipline and vocabulary.\n")
    pr = run_pipeline(canon["base"]["internal_id"], canon["target"]["internal_id"], paths.read_json(paths.FINAL_ANSWER))
    top = [r for r in pr.stage3 if r.pattern == "shared_principle"][0]
    w(f"**[ORGANISER]** Stage 3 independently proposes the same relation, status `{top.status}` "
      f"(never auto-verified), defensible={top.defensible}:\n\n> {top.explanation}\n")
    rep = pr.stage4[0]
    w(f"Stage 4 application report: **{rep.application_label}**; lineage claim: `{rep.lineage_claim}`. Limitations:")
    for lim in rep.limitations[:3]:
        w(f"- {lim}")
    w("")

    # 7 ------------------------------------------------------------------
    w("## 7. One-shot final submission\n")
    registry = build_flag_registry(paths.read_json(paths.FINAL_ANSWER), secret)
    deadline = dt.datetime.now(dt.timezone.utc) + dt.timedelta(hours=1)
    svc = FinalSubmissionService(store, registry, deadline.isoformat(), secret=secret)
    form = {
        "base_id": info["starting_paper"],
        "target_id": canon["target"]["participant_id"],
        "principle": "Both papers reconstruct a hidden branching tree, including internal nodes nobody observes (routers / "
                     "common ancestors), from measurements available only at the leaves (receivers / living species): "
                     "leaves that share more of the hidden tree look more similar (correlated loss / small distance).",
        "application": "Nextstrain",
        "paper_evidence": "P05 abstract; P12 p.5 (problem similar to phylogenetic inference) and Alg. 1 p.13 (NJ); "
                          "P08 p.5 (multicast loss as a special case of DNA evolution model); P03 abstract.",
        "application_evidence": "https://doi.org/10.1093/bioinformatics/bty407 ; "
                                "https://docs.nextstrain.org/projects/augur/en/stable/usage/cli/ancestral.html",
        "limitations": "Shared principle only - no historical lineage from P05 to Nextstrain. Nextstrain uses maximum "
                       "likelihood (IQ-TREE) and TreeTime rather than neighbor-joining; networking observes the root, "
                       "phylogenetics does not.",
    }
    receipt = svc.submit(team["team_id"], form)
    w(f"Receipt shown to the team: `{receipt}`")
    try:
        svc.submit(team["team_id"], form)
    except PermissionError as exc:
        w(f"\nSecond attempt refused: \"{exc}\"")
    w(f"\nStatus before the deadline: `{svc.participant_status(team['team_id'])}`\n")

    # 8 ------------------------------------------------------------------
    w("## 8. [ORGANISER] After the deadline: answer key and results\n")
    after = deadline + dt.timedelta(minutes=1)
    w(f"Status shown to the team after the deadline: `{svc.participant_status(team['team_id'], at=after)}`\n")
    final = store.final_submissions()[team["team_id"]]
    w(f"Organiser evaluation: `{final['evaluation']}`\n")
    fa = paths.read_json(paths.FINAL_ANSWER)
    w(f"Answer key: target **{fa['target_participant_id']}**, application **{fa['application']['canonical']}**, "
      f"lineage claim `{fa['application']['lineage_claim']}`.\n\n> {fa['hidden_connection']['statement']}\n")
    w("Leaderboard (best valid score per team, private split):\n")
    for row in store.best_scores("private"):
        w(f"- {row['team']}: {row['weighted_f1']:.4f}")
    w("")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}  (sandbox: {tmp})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
